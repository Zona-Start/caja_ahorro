'use client';

import { DataTable } from '@repo/shadcn/table/data-table';
import { DataTableSkeleton } from '@repo/shadcn/table/data-table-skeleton';
import { columns } from './transaction-tables/columns';
import { usePaginatedTransactionType } from '../hooks/use-query-transaction-type';

interface TransactionTypeListProps {
  initialPage: number;
  initialSearch?: string | null;
  initialLimit: number;
}

export default function TransactionTypeList({
  initialPage,
  initialSearch,
  initialLimit,
}: TransactionTypeListProps) {
  const filters = {
    page: initialPage,
    limit: initialLimit,
    ...(initialSearch && { search: initialSearch }),
  };

  const { data, isLoading } = usePaginatedTransactionType(filters);

  if (isLoading) {
    return <DataTableSkeleton columnCount={6} rowCount={initialLimit} />;
  }

  return (
    <DataTable
      columns={columns}
      data={data?.data || []}
      totalItems={data?.meta.totalCount || 0}
      pageSizeOptions={[10, 20, 30, 40, 50]}
    />
  );
}
